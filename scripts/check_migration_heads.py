"""The host's migration history has exactly one head.

Every module's tables are autogenerated into ``host/migrations/versions/``,
and two pull requests that each add a revision off the same parent leave the
history with two heads once both merge. Nothing breaks visibly — ``make
migrate`` runs ``upgrade heads`` and applies them all — but ``make migration``
(``revision --autogenerate``) then refuses with "Multiple heads are present",
and ``make downgrade`` (``downgrade -1``) rolls back whichever branch alembic
picks (#107). The fix is an empty ``alembic merge heads`` revision; this check
makes the split fail CI instead of surfacing in the next contributor's
``make migration``.

Reads the revision files only — no database, no ``env.py``.

Exit 0 with one head, 1 otherwise.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from alembic.script import ScriptDirectory

ROOT = Path(__file__).resolve().parents[1]
MIGRATIONS = ROOT / "host" / "migrations"


def heads(migrations: Path) -> list[str]:
    return list(ScriptDirectory(str(migrations)).get_heads())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--migrations", type=Path, default=MIGRATIONS)
    args = parser.parse_args(argv)

    found = heads(args.migrations)
    if len(found) == 1:
        print(f"One migration head: {found[0]}")
        return 0
    print(f"Expected one migration head, found {len(found)}: {', '.join(sorted(found))}")
    if found:
        print(
            "Add an empty merge revision from the repo root:\n"
            '  uv run --project host alembic -c host/alembic.ini merge heads -m "merge heads"'
        )
    return 1


if __name__ == "__main__":
    sys.exit(main())
