"""Store phase: stage a step's objects, then complete it in one fenced transaction.

1. **Stage.** Generated bytes (a display copy, renditions) go to attempt-unique
   keys (``storage.keys``: the lease token is in the key), each recorded as an
   object intent first, in its own short session - before any write lock is
   held, which SQLite would otherwise make the intent wait on.
2. **Complete.** One transaction: the image lock, the run's conditional
   ``UPDATE`` (lost lease → roll back, delete the staged objects), the typed
   writes of the built-in steps, the intents of the new keys cleared and those
   of the replaced keys added, then the next planning round - dependants
   claimed, ``ImageProcessed`` decided - all committing together.
   A ``prompt:*`` run also writes its ``images_prompt_result`` row there
   (:func:`sm_images.ai.results.record_prompt_run`), and records the prompt's
   revision as the run's version. ``storage_bytes`` and the storage hold move
   here too; a growing image's hold is swapped between the two phases
   (``storage_hold``).
3. **After the commit**, the replaced objects are deleted. A failed delete
   leaves its intent for the janitor.
"""

from __future__ import annotations

import logging
import uuid
from dataclasses import dataclass, field
from datetime import UTC, datetime
from functools import partial
from typing import Any

from simple_module_db import finalize_session, independent_session
from simple_module_db.callbacks import register_on_commit
from sqlalchemy import delete

from sm_images.errors import StorageQuotaExceeded
from sm_images.models import ObjectIntent
from sm_images.pipeline import publish, registry, storage_hold
from sm_images.pipeline.advance import advance_locked, conclude
from sm_images.pipeline.claim import complete, lock_image
from sm_images.pipeline.cycle import release
from sm_images.pipeline.runtime import Runtime
from sm_images.pipeline.step import StepOutcome
from sm_images.storage import keys as storage_keys
from sm_images.storage.intents import clear_intents, object_intent

__all__ = ["Staged", "complete_step", "stage"]

logger = logging.getLogger(__name__)
JPEG = "image/jpeg"
EXIF = "exif"
RENDITIONS = "renditions"


@dataclass
class Staged:
    keys: list[str] = field(default_factory=list)
    display_key: str | None = None
    display_bytes: int = 0
    renditions: dict[str, tuple[str, int, int, int]] = field(default_factory=dict)
    attempt: str = ""


async def _drop(runtime: Runtime, keys: list[str]) -> None:
    """Delete objects nothing references, then their intents. Best effort: an
    object whose delete fails keeps its intent, and the janitor retries."""
    if not keys:
        return
    try:
        await runtime.store().delete_keys(keys)
        async with independent_session(runtime.session_factory) as s:
            await s.execute(delete(ObjectIntent).where(ObjectIntent.key.in_(keys)))
    except Exception:
        logger.warning("images.pipeline.object_cleanup_failed keys=%s", keys, exc_info=True)


async def stage(runtime: Runtime, loaded: Any, staging: Any) -> Staged:
    """Write the step's generated objects under intents (completed outcomes only)."""
    out = Staged()
    ids = (loaded.tenant, str(loaded.collection_id), str(loaded.image_id))
    # A fresh nonce per execution, not the lease token: a redelivered message
    # runs twice under one token, and its loser must never share (and so
    # delete) the winner's keys. The token only fences the database.
    attempt = out.attempt = uuid.uuid4().hex
    writes: list[tuple[str, bytes, str]] = []
    if staging.display is not None and loaded.mutates_display:
        data, content_type = staging.display
        out.display_key = storage_keys.display_key(*ids, loaded.display_generation + 1, attempt)
        out.display_bytes = len(data)
        writes.append((out.display_key, data, content_type))
    renditions = staging.renditions if loaded.step == RENDITIONS else None
    for size, (data, width, height) in (renditions or {}).items():
        key = storage_keys.rendition_key(*ids, size, loaded.display_generation, attempt)
        out.renditions[size] = (key, width, height, len(data))
        writes.append((key, data, JPEG))
    out.keys = [w[0] for w in writes]
    if not writes:
        return out
    async with object_intent(out.keys, session_factory=runtime.session_factory):
        store = runtime.store()
        try:
            for key, data, content_type in writes:
                await store.put(key, data, content_type=content_type, size=len(data))
        except Exception:
            await _drop(runtime, out.keys)
            raise
    return out


async def _requeue(runtime: Runtime, loaded: Any, lease_s: int) -> None:
    """The display moved under a run we still own: give it back and plan again."""
    async with runtime.session_factory() as db:
        locked = await lock_image(db, loaded.tenant, loaded.image_id)
        now = datetime.now(UTC)
        if locked is not None and await release(
            db, loaded.tenant, loaded.image_id, loaded.step, loaded.token, now
        ):
            advanced = await advance_locked(
                db, loaded.tenant, loaded.image_id, locked, now, lease_s
            )
            await conclude(db, runtime, loaded.tenant, loaded.image_id, advanced)
        await finalize_session(db)


async def _publish(
    db: Any, loaded: Any, locked: Any, staged: Staged, staging: Any, version: int | None
) -> list[str] | None:
    """The built-in writes (``staging`` is ``None`` unless the step completed).
    ``None`` = a fence failed; the transaction must not commit."""
    tenant, image_id = loaded.tenant, loaded.image_id
    replaced: list[str] = []
    if staged.display_key is not None:
        generation = loaded.display_generation + 1
        if not await publish.publish_display(
            db,
            tenant,
            image_id,
            staged.display_key,
            generation,
            loaded.step,
            version,
            staged.display_bytes,
        ):
            return None
        if locked.display_key:
            replaced.append(locked.display_key)
        await publish.invalidate_renditions(db, tenant, image_id)
        await publish.invalidate_other_mutators(db, tenant, image_id, loaded.step)
    if staged.renditions:
        if locked.display_generation != loaded.display_generation:
            return None  # cut from a display copy that has since been replaced
        replaced += await publish.replace_renditions(
            db, tenant, image_id, staged.renditions, loaded.display_generation
        )
        await publish.touch_image(db, tenant, image_id, datetime.now(UTC))
    if staging is not None and staging.exif is not None and loaded.step == EXIF:
        await publish.store_exif(db, tenant, image_id, staging.exif)
    return replaced


async def _hold(
    runtime: Runtime, loaded: Any, staged: Staged, outcome: StepOutcome
) -> tuple[storage_hold.Planned | None, Staged, StepOutcome]:
    """Swap the image's hold first when the staged objects grow it. Refused, or
    billing unusable (fail closed): the objects go, nothing is published, the
    step fails. A swap of the image still pending: the objects go and it
    raises - the run keeps its lease until it lapses, then reconcile runs the
    step again."""
    try:
        return await storage_hold.reserve(runtime, loaded, staged), staged, outcome
    except storage_hold.HoldBusy:
        await _drop(runtime, staged.keys)
        raise
    except StorageQuotaExceeded as exc:
        failed = StepOutcome.failed("quota_exceeded", exc.detail)
    except Exception as exc:
        logger.warning("images.pipeline.storage_hold_failed step=%s", loaded.step, exc_info=True)
        failed = StepOutcome.failed("storage_error", f"{type(exc).__name__}: {exc}"[:2000])
    await _drop(runtime, staged.keys)
    return None, Staged(), failed


async def complete_step(
    runtime: Runtime, loaded: Any, outcome: StepOutcome, staging: Any, *, version: int | None
) -> bool:
    """Stage, then complete in one transaction. ``False``: the lease was lost or
    a fence failed, and nothing this attempt produced was kept."""
    lease_s = runtime.settings().step_lease_seconds
    prompt = loaded.step.startswith(registry.PROMPT_PREFIX)
    staged = Staged()
    if outcome.status == "completed":
        try:
            staged = await stage(runtime, loaded, staging)
        except Exception as exc:
            logger.warning("images.pipeline.stage_failed step=%s", loaded.step, exc_info=True)
            outcome = StepOutcome.failed("storage_error", f"{type(exc).__name__}: {exc}"[:2000])
    planned, staged, outcome = await _hold(runtime, loaded, staged, outcome)
    requeue = False
    async with runtime.session_factory() as db:
        locked = await lock_image(db, loaded.tenant, loaded.image_id)
        # Read the clock only once the lock is held: a completion that waited
        # on it past its lease must be rejected, and later leases start now.
        now = datetime.now(UTC)
        ok = locked is not None and await complete(
            db,
            loaded.tenant,
            loaded.image_id,
            loaded.step,
            loaded.token,
            outcome,
            now,
            version=version,
            revision=version if prompt else None,
        )
        writes = staging if outcome.status == "completed" else None
        replaced = await _publish(db, loaded, locked, staged, writes, version) if ok else None
        if replaced is not None and not await storage_hold.record(db, runtime, loaded, planned):
            replaced = None  # the total or the hold moved since: plan again
        if replaced is None:
            await db.rollback()
            requeue = ok  # still ours: only the display fence failed
        else:
            if prompt:
                from sm_images.ai.results import record_prompt_run

                await record_prompt_run(db, loaded, outcome, writes)
            await clear_intents(db, staged.keys)
            await publish.add_intents(db, replaced)
            advanced = await advance_locked(
                db, loaded.tenant, loaded.image_id, locked, now, lease_s
            )
            await conclude(db, runtime, loaded.tenant, loaded.image_id, advanced)
            if replaced:
                register_on_commit(db, partial(_drop, runtime, replaced))
        await finalize_session(db)
    if replaced is None:
        await _drop(runtime, staged.keys)
        await storage_hold.abandon(runtime, planned)
        if requeue:
            try:
                await _requeue(runtime, loaded, lease_s)
            except Exception:  # the lease expires and reconcile reclaims it
                logger.warning("images.pipeline.requeue_failed step=%s", loaded.step, exc_info=True)
        return False
    return True
